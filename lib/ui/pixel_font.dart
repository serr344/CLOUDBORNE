import 'dart:math' as math;
import 'dart:ui';

/// Hand-drawn 5x7 pixel font: upper and lower case letters, digits and common punctuation.
/// Unknown characters are drawn as '?'.
///
/// Every glyph sits in a 9 row box: row 0 is empty headroom, rows 1-7 are the glyph and
/// row 8 holds descenders (the comma's tail, g, j, p, q, y).
class PixelFont {
  static const int glyphW = 5;
  static const int advance = 6;
  static const int height = 9;

  static double width(String text, [double scale = 1]) => text.isEmpty ? 0 : (text.length * advance - 1) * scale;

  /// Draws [text]. [progress] is how much of it has been "typed", in characters
  /// (2.5 = two letters done and half of the third); letters appear column by column.
  static void draw(
    Canvas c,
    String text,
    double x,
    double y,
    Paint paint, {
    double sx = 1,
    double sy = 1,
    double progress = double.infinity,
  }) {
    for (var i = 0; i < text.length; i++) {
      if (progress <= i) break;
      final pixels = _pixels(text[i]);
      final part = progress - i;
      final count = part >= 1 ? pixels.length : (pixels.length * part).floor();
      final gx = x + i * advance * sx;
      for (var k = 0; k < count; k++) {
        final p = pixels[k];
        final top = y + p.y * sy;
        c.drawRect(Rect.fromLTWH(gx + p.x * sx, math.min(top, top + sy), sx.abs(), sy.abs()), paint);
      }
    }
  }

  /// Splits [text] into lines of at most [max] characters, breaking at spaces.
  static List<String> wrap(String text, int max) {
    final out = <String>[];
    var line = '';
    for (final w in text.split(' ')) {
      if (line.isEmpty) {
        line = w;
      } else if (line.length + 1 + w.length <= max) {
        line += ' $w';
      } else {
        out.add(line);
        line = w;
      }
    }
    if (line.isNotEmpty) out.add(line);
    return out;
  }

  /// Draws wrapped [lines] being typed out. [progress] counts characters of the original text,
  /// so the space where a line was broken counts as one character.
  static void drawLines(Canvas c, List<String> lines, double x, double y, Paint paint,
      {double lineHeight = 11, double progress = double.infinity}) {
    var left = progress;
    for (var i = 0; i < lines.length && left > 0; i++) {
      draw(c, lines[i], x, y + i * lineHeight, paint, progress: left);
      left -= lines[i].length + 1;
    }
  }

  /// The pixels of one glyph, column by column.
  static List<math.Point<int>> _pixels(String ch) => _cache.putIfAbsent(ch, () {
        final rows = _rows(ch);
        final out = <math.Point<int>>[];
        for (var col = 0; col < glyphW; col++) {
          for (var row = 0; row < height; row++) {
            if (rows[row][col] == '#') out.add(math.Point(col, row));
          }
        }
        return out;
      });

